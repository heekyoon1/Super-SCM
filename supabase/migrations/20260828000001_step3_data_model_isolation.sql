create table if not exists core.forecast_setting (
  setting_key text primary key default 'default',
  train_start date,
  train_end date,
  test_start date,
  test_end date,
  granularity text not null default 'MONTH',
  active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint forecast_setting_date_order check (
    train_start is null or train_end is null or train_start <= train_end
  ),
  constraint forecast_setting_test_order check (
    test_start is null or test_end is null or test_start <= test_end
  ),
  constraint forecast_setting_non_overlap check (
    train_end is null or test_start is null or train_end < test_start
  )
);

insert into core.forecast_setting (setting_key)
values ('default')
on conflict (setting_key) do nothing;

