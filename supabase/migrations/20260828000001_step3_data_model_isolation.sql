-- These are the only application-facing paths for forecast training and test scoring.
create or replace view core.v_train_demand as
select
  uh.item_id,
  uh.usage_date,
  uh.quantity,
  uh.batch_id,
  uh.source_type,
  uh.loaded_at,
  uh.source_record_id,
  fs.setting_key
from raw.usage_history uh
join core.forecast_setting fs on fs.setting_key = 'default' and fs.active = true
where fs.train_start is not null
  and fs.train_end is not null
  and uh.usage_date between fs.train_start and fs.train_end
  and not exists (
    select 1
    from core.outlier_rule orule
    where orule.active = true
      and orule.exclude_from_training = true
      and orule.rule_code = uh.event_type
  );

create or replace view core.v_test_actual as
select
  uh.item_id,
  uh.usage_date,
  uh.quantity,
  uh.batch_id,
  uh.source_type,
  uh.loaded_at,
  uh.source_record_id,
  fs.setting_key
from raw.usage_history uh
join core.forecast_setting fs on fs.setting_key = 'default' and fs.active = true
where fs.test_start is not null
  and fs.test_end is not null
  and uh.usage_date between fs.test_start and fs.test_end;

create or replace view analytics.v_data_coverage as
with data_window as (
  select min(usage_date) as data_start, max(usage_date) as data_end
  from raw.usage_history
), setting as (
  select train_start, train_end, test_start, test_end, granularity
  from core.forecast_setting
  where setting_key = 'default' and active = true
)
select
  data_window.data_start,
  data_window.data_end,
  setting.train_start,
  setting.train_end,
  setting.test_start,
  setting.test_end,
  (select count(*) from core.v_train_demand) as train_row_count,
  (select count(*) from core.v_test_actual) as test_row_count,
  setting.granularity,
  (setting.train_start is not null and setting.train_end is not null and data_window.data_start <= setting.train_start and data_window.data_end >= setting.train_end) as train_window_ok,
  (setting.test_start is not null and setting.test_end is not null and data_window.data_start <= setting.test_start and data_window.data_end >= setting.test_end) as test_window_ok
from data_window cross join setting;

grant select on core.v_train_demand, core.v_test_actual to authenticated;
grant select on analytics.v_data_coverage to authenticated;

