alter table core.forecast_setting add column if not exists reference_model_id text not null default 'MA_3M';
alter table core.forecast_setting add column if not exists tie_break_rule text not null default 'ABS_BIAS,RMSE,MAE,MODEL_ID';
alter table core.forecast_setting drop constraint if exists forecast_setting_champion_metric_check;
alter table core.forecast_setting add constraint forecast_setting_champion_metric_check check (champion_metric in ('WAPE','MAPE','RMSE','MAE'));

create table if not exists core.backtest_run (
  backtest_run_id uuid primary key default gen_random_uuid(),
  forecast_run_id uuid not null references core.forecast_run(run_id) on delete restrict,
  test_start date not null,
  test_end date not null,
  metric text not null default 'WAPE',
  status text not null default 'RUNNING' check (status in ('RUNNING','SUCCESS','FAILED')),
  started_at timestamptz not null default now(),
  finished_at timestamptz,
  triggered_by uuid references auth.users(id),
  message text
);

create table if not exists core.model_performance (
  performance_id bigint generated by default as identity primary key,
  run_id uuid not null references core.forecast_run(run_id) on delete restrict,
  backtest_run_id uuid not null references core.backtest_run(backtest_run_id) on delete cascade,
  forecast_run_id uuid not null references core.forecast_run(run_id) on delete restrict,
  model_id text not null,
  model_version text not null,
  item_id text not null,
  n_periods integer not null default 0,
  wape numeric,
  mape numeric,
  bias numeric,
  rmse numeric,
  mae numeric,
  baseline_improvement numeric,
  rank integer,
  calculation_status text not null default 'SUCCESS',
  reason_code text,
  calculated_at timestamptz not null default now(),
  unique (backtest_run_id, model_id, item_id)
);

comment on table core.model_performance is 'WAPE=100*sum(abs(F-A))/sum(abs(A)); MAPE=100*mean(abs(F-A)/abs(A)) over A<>0; Bias=mean(F-A), positive means over-forecast; RMSE and MAE use periods with both F and A. Missing/zero denominators remain null with reason_code.';

create table if not exists core.champion_model (
  champion_id bigint generated by default as identity primary key,
  backtest_run_id uuid not null references core.backtest_run(backtest_run_id) on delete restrict,
  item_id text not null,
  champion_model_id text not null,
  model_version text not null,
  champion_metric text not null,
  champion_metric_value numeric,
  wape numeric,
  mape numeric,
  bias numeric,
  rmse numeric,
  candidate_performance jsonb not null default '[]'::jsonb,
  selection_reason text not null,
  selection_method text not null check (selection_method in ('AUTO','MANUAL')),
  selected_at timestamptz not null default now(),
  selected_by uuid references auth.users(id)
);

create table if not exists core.champion_selection_issue (
  issue_id bigint generated by default as identity primary key,
  backtest_run_id uuid not null references core.backtest_run(backtest_run_id) on delete cascade,
  item_id text not null,
  reason_code text not null,
  created_at timestamptz not null default now(),
  unique (backtest_run_id, item_id)
);

create index if not exists model_performance_item_idx on core.model_performance(item_id, backtest_run_id);
create index if not exists champion_model_item_idx on core.champion_model(item_id, selected_at desc);

