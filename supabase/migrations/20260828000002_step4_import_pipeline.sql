-- STEP 4: staged import pipeline. Additive migration; existing raw data is preserved.
create table if not exists core.upload_batch (
  batch_id uuid primary key default gen_random_uuid(),
  file_name text not null,
  import_type text not null check (import_type in ('usage_history', 'business_event', 'sales_order', 'item_substitute')),
  import_mode text not null check (import_mode in ('append', 'upsert', 'replace')),
  total_rows integer not null default 0,
  success_rows integer not null default 0,
  warning_rows integer not null default 0,
  error_rows integer not null default 0,
  status text not null default 'STAGED' check (status in ('STAGED', 'VALIDATING', 'VALIDATED', 'READY', 'IMPORTED', 'VALIDATION_FAILED', 'ROLLED_BACK', 'FAILED')),
  uploaded_by uuid not null references auth.users(id),
  uploaded_at timestamptz not null default now(),
  imported_at timestamptz,
  mapping jsonb not null default '{}'::jsonb,
  rollback_supported boolean not null default true
);

create table if not exists core.import_staging (
  staging_id bigint generated by default as identity primary key,
  batch_id uuid not null references core.upload_batch(batch_id) on delete cascade,
  row_number integer not null,
  original_data jsonb not null,
  mapped_data jsonb not null default '{}'::jsonb,
  validation_status text not null default 'ERROR' check (validation_status in ('SUCCESS', 'WARNING', 'ERROR')),
  created_at timestamptz not null default now(),
  unique (batch_id, row_number)
);

create table if not exists core.column_mapping (
  mapping_id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  import_type text not null check (import_type in ('usage_history', 'business_event', 'sales_order', 'item_substitute')),
  mapping_name text not null default 'default',
  mapping jsonb not null,
  updated_at timestamptz not null default now(),
  unique (user_id, import_type, mapping_name)
);

create table if not exists core.validation_error (
  validation_error_id bigint generated by default as identity primary key,
  batch_id uuid not null references core.upload_batch(batch_id) on delete cascade,
  row_number integer not null,
  field_name text not null,
  error_code text not null,
  error_message text not null,
  severity text not null check (severity in ('WARNING', 'ERROR')),
  original_value text,
  created_at timestamptz not null default now()
);

create index if not exists import_staging_batch_idx on core.import_staging(batch_id, row_number);
create index if not exists validation_error_batch_idx on core.validation_error(batch_id, row_number);

alter table core.upload_batch enable row level security;
alter table core.import_staging enable row level security;
alter table core.column_mapping enable row level security;
alter table core.validation_error enable row level security;
grant select, insert, update on core.upload_batch, core.import_staging, core.column_mapping, core.validation_error to authenticated;
grant usage, select on all sequences in schema core to authenticated;

