-- STEP 9: effective lead time and forecast-based inventory projection.
-- Missing inventory/lead time/forecast remains NULL with a reason code; no fake zero/default days.

create table if not exists raw.inventory_snapshot (
  snapshot_id bigint generated by default as identity primary key,
  item_id text not null,
  snapshot_date date not null,
  available_inventory numeric,
  batch_id uuid,
  source_type text,
  loaded_at timestamptz default now(),
  source_record_id text
);
create table if not exists raw.purchase_order (
  purchase_order_id text primary key,
  item_id text not null,
  scheduled_receipt_date date,
  quantity numeric,
  status text,
  batch_id uuid,
  source_type text,
  loaded_at timestamptz default now(),
  source_record_id text
);
create table if not exists raw.soft_allocation (
  allocation_id text primary key,
  item_id text not null,
  allocation_date date,
  quantity numeric,
  status text,
  batch_id uuid,
  source_type text,
  loaded_at timestamptz default now(),
  source_record_id text
);
create table if not exists raw.lead_time_observation (
  observation_id bigint generated by default as identity primary key,
  item_id text not null,
  supplier_id text not null,
  order_date date,
  receipt_date date,
  lead_time_days numeric,
  batch_id uuid,
  source_type text,
  loaded_at timestamptz default now(),
  source_record_id text
);

create index if not exists inventory_snapshot_item_date_idx on raw.inventory_snapshot(item_id, snapshot_date desc);
create index if not exists purchase_order_item_receipt_idx on raw.purchase_order(item_id, scheduled_receipt_date);
create index if not exists soft_allocation_item_date_idx on raw.soft_allocation(item_id, allocation_date);
create index if not exists lead_time_observation_item_idx on raw.lead_time_observation(item_id, supplier_id);
revoke all on raw.inventory_snapshot, raw.purchase_order, raw.soft_allocation, raw.lead_time_observation from anon, authenticated;
alter table raw.inventory_snapshot enable row level security;
alter table raw.purchase_order enable row level security;
alter table raw.soft_allocation enable row level security;
alter table raw.lead_time_observation enable row level security;

create table if not exists core.lead_time_policy (
  policy_id bigint generated by default as identity primary key,
  item_id text not null,
  supplier_id text not null,
  confirmed_lead_time_days numeric,
  effective_from date not null default current_date,
  effective_to date,
  active boolean not null default true,
  updated_by uuid references auth.users(id),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (item_id, supplier_id, effective_from)
);
create table if not exists core.lead_time_policy_history (
  history_id bigint generated by default as identity primary key,
  policy_id bigint,
  action text not null,
  before jsonb,
  after jsonb,
  changed_by uuid references auth.users(id),
  changed_at timestamptz not null default now()
);
create table if not exists core.inventory_projection_setting (
  setting_key text primary key default 'default',
  warning_lead_time_rule text not null default 'STOCKOUT_AFTER_RECEIPT',
  confirmed_order_statuses text[] not null default array['CONFIRMED','ALLOCATED'],
  soft_allocation_statuses text[] not null default array['ACTIVE','RESERVED'],
  soft_allocation_source_configured boolean not null default false,
  updated_by uuid references auth.users(id),
  updated_at timestamptz not null default now()
);
insert into core.inventory_projection_setting(setting_key) values ('default') on conflict (setting_key) do nothing;

create or replace function core.record_lead_time_policy_history()
returns trigger language plpgsql security definer set search_path = core, public as $$
begin
  insert into core.lead_time_policy_history(policy_id, action, before, after, changed_by)
  values (coalesce(new.policy_id, old.policy_id), tg_op, case when tg_op = 'INSERT' then null else to_jsonb(old) end, case when tg_op = 'DELETE' then null else to_jsonb(new) end, coalesce(new.updated_by, auth.uid()));
  return coalesce(new, old);
end; $$;
drop trigger if exists lead_time_policy_history_trigger on core.lead_time_policy;
create trigger lead_time_policy_history_trigger after insert or update or delete on core.lead_time_policy for each row execute function core.record_lead_time_policy_history();
drop trigger if exists lead_time_policy_updated_at on core.lead_time_policy;
create trigger lead_time_policy_updated_at before update on core.lead_time_policy for each row execute function core.set_updated_at();

